//! The library-level entry points: ABI version and engine version.

use std::ffi::CStr;

use ace_ffi::{ace_abi_minor, ace_abi_version, ace_engine_version, ACE_ABI_MINOR, ACE_ABI_VERSION};

#[test]
fn abi_version_is_one() {
    assert_eq!(ace_abi_version(), 1);
    assert_eq!(ace_abi_version(), ACE_ABI_VERSION);
}

/// Adding functions raises the minor version and leaves the major version alone.
#[test]
fn abi_minor_is_one_for_the_storage_functions() {
    assert_eq!(ace_abi_minor(), 1);
    assert_eq!(ace_abi_minor(), ACE_ABI_MINOR);
}

#[test]
fn engine_version_is_the_crate_version() {
    let pointer = ace_engine_version();
    assert!(!pointer.is_null());
    // SAFETY: `ace_engine_version` returns a NUL-terminated string with static storage duration.
    let text = unsafe { CStr::from_ptr(pointer) };
    assert_eq!(text.to_str(), Ok(env!("CARGO_PKG_VERSION")));
    assert_eq!(text.to_str(), Ok("0.8.0"));
}

/// The JVM bindings (generated by `tools/ace-genbindings0.8.0.py`) hard-code these offsets from
/// the header; a change in the Rust structs must show up here first.
#[test]
fn struct_layouts_are_the_documented_ones() {
    use std::mem::{offset_of, size_of};

    use ace_ffi::{AceConfig, AceLimits};

    // ABI 1.0 ended at `reserved` (56 bytes); 1.1 appends behind it, so a 1.0 caller that declares
    // `struct_size == 56` still works.
    assert_eq!(size_of::<AceConfig>(), 112);
    assert_eq!(offset_of!(AceConfig, struct_size), 0);
    assert_eq!(offset_of!(AceConfig, profile), 8);
    assert_eq!(offset_of!(AceConfig, block_size), 16);
    assert_eq!(offset_of!(AceConfig, threads), 24);
    assert_eq!(offset_of!(AceConfig, memory_budget), 32);
    assert_eq!(offset_of!(AceConfig, block_size_policy), 40);
    assert_eq!(offset_of!(AceConfig, access_hint), 44);
    assert_eq!(offset_of!(AceConfig, write_index), 48);
    assert_eq!(offset_of!(AceConfig, numeric_specialization), 49);
    assert_eq!(offset_of!(AceConfig, float_specialization), 50);
    assert_eq!(offset_of!(AceConfig, reserved), 51);
    assert_eq!(offset_of!(AceConfig, schema), 56);
    assert_eq!(offset_of!(AceConfig, dictionary), 64);
    assert_eq!(offset_of!(AceConfig, dictionary_scope), 72);
    assert_eq!(offset_of!(AceConfig, segmentation), 76);
    assert_eq!(offset_of!(AceConfig, segment_window), 80);
    assert_eq!(offset_of!(AceConfig, segment_min), 88);
    assert_eq!(offset_of!(AceConfig, segment_max), 96);
    assert_eq!(offset_of!(AceConfig, max_segments), 104);

    assert_eq!(size_of::<ace_ffi::AceColumn>(), 8);

    assert_eq!(size_of::<AceLimits>(), 56);
    assert_eq!(offset_of!(AceLimits, struct_size), 0);
    assert_eq!(offset_of!(AceLimits, max_output_size), 8);
    assert_eq!(offset_of!(AceLimits, max_block_size), 16);
    assert_eq!(offset_of!(AceLimits, max_encoded_block_size), 24);
    assert_eq!(offset_of!(AceLimits, max_transforms), 32);
    assert_eq!(offset_of!(AceLimits, max_dictionary_size), 40);
    assert_eq!(offset_of!(AceLimits, max_blocks), 48);
}
