//! `ace-corpus` — writes one deterministic workload (or false-positive case) to a file (used by
//! the demo and scripts).
//!
//! ```text
//! ace-corpus <workload> <bytes> <output>
//! ace-corpus --list
//! ```

use std::process::ExitCode;

use ace_corpus::{FalsePositiveCase, Workload};

/// Parses arguments, generates the workload and writes it.
fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.as_slice() {
        [flag] if flag == "--list" => {
            Workload::ALL
                .iter()
                .for_each(|workload| println!("{workload}"));
            FalsePositiveCase::ALL
                .iter()
                .for_each(|case| println!("{}", case.name()));
            ExitCode::SUCCESS
        }
        [name, bytes, output] => match generate(name, bytes, output) {
            Ok(()) => ExitCode::SUCCESS,
            Err(message) => {
                eprintln!("ace-corpus: {message}");
                ExitCode::FAILURE
            }
        },
        _ => {
            eprintln!("usage: ace-corpus <workload> <bytes> <output> | ace-corpus --list");
            ExitCode::from(2)
        }
    }
}

/// Validates the arguments and writes the generated bytes.
fn generate(name: &str, bytes: &str, output: &str) -> Result<(), String> {
    let bytes: usize = parse_size(bytes).ok_or_else(|| format!("invalid size `{bytes}`"))?;
    let data = match Workload::from_name(name) {
        Some(workload) => workload.generate(bytes),
        None => FalsePositiveCase::ALL
            .into_iter()
            .find(|case| case.name() == name)
            .ok_or_else(|| format!("unknown workload `{name}` (see --list)"))?
            .generate(bytes),
    };
    std::fs::write(output, data).map_err(|error| format!("writing {output}: {error}"))
}

/// Parses `123`, `64k`, `16m` or `1g` (binary multiples).
fn parse_size(text: &str) -> Option<usize> {
    let (digits, multiplier) = match text.chars().last()?.to_ascii_lowercase() {
        'k' => (&text[..text.len() - 1], 1usize << 10),
        'm' => (&text[..text.len() - 1], 1 << 20),
        'g' => (&text[..text.len() - 1], 1 << 30),
        _ => (text, 1),
    };
    digits.parse::<usize>().ok()?.checked_mul(multiplier)
}
